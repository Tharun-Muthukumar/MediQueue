/**
 * RQ2 — How accurate is the rolling-median ETA against actual call times?
 * Replays synthetic clinic sessions through the production queue policy and ETA engine,
 * then compares the prediction made at check-in with the actual wait, against a
 * fixed-duration baseline (12 min × patients ahead). Writes docs/results/eta-evaluation.md.
 *
 *   npm run eval:eta            (defaults: 30 sessions)
 *   npm run eval:eta -- 60      (more sessions)
 */
import fs from 'node:fs';
import path from 'node:path';
import { rng, simulateSession } from '../src/domain/simulation';
import { mean, median, percentile } from '../src/shared/util';

const SESSIONS = Number(process.argv[2] ?? 30);
const SEED = 4242;
const random = rng(SEED);

const profiles = [
  { code: 'D01', medianMin: 12, slotMin: 15, slots: 16 },
  { code: 'D02', medianMin: 9, slotMin: 15, slots: 16 },
  { code: 'D03', medianMin: 17, slotMin: 20, slots: 12 },
];

interface Row { doctor: string; session: number; predicted: number; baseline: number; actual: number }
const rows: Row[] = [];

for (const p of profiles) {
  let history: number[] = [];
  for (let s = 0; s < SESSIONS; s++) {
    const start = new Date(Date.UTC(2026, 0, 1 + s, 3, 30));
    const slots = Array.from({ length: p.slots }, (_, i) => ({ startAt: new Date(start.getTime() + i * p.slotMin * 60000), booked: random() < 0.7 }));
    const sim = simulateSession({
      slots,
      walkIns: 2 + Math.floor(random() * 3),
      sessionStart: start,
      sessionEnd: new Date(start.getTime() + p.slots * p.slotMin * 60000),
      medianConsultMin: p.medianMin,
      defaultMin: 12,
      ratio: 2,
      noShowRate: 0.08,
      history,
      random,
    });
    history = sim.history.slice(0, 30);
    // Skip the first session per doctor: no history yet, both methods use the default.
    if (s === 0) continue;
    for (const v of sim.visits) {
      if (!v.calledAt || !v.checkedInAt || v.predictedWaitSec === null || v.baselineWaitSec === null) continue;
      rows.push({
        doctor: p.code,
        session: s,
        predicted: v.predictedWaitSec / 60,
        baseline: v.baselineWaitSec / 60,
        actual: (v.calledAt.getTime() - v.checkedInAt.getTime()) / 60000,
      });
    }
  }
}

const err = (k: 'predicted' | 'baseline', subset = rows) => subset.map((r) => Math.abs(r[k] - r.actual));
const inBand = rows.filter((r) => r.actual >= r.predicted * 0.8 - 1 && r.actual <= r.predicted * 1.25 + 1).length;
const f = (n: number | null) => (n === null ? '–' : n.toFixed(2));

const perDoctor = profiles.map((p) => {
  const sub = rows.filter((r) => r.doctor === p.code);
  return `| ${p.code} | ${p.medianMin} | ${sub.length} | ${f(mean(err('predicted', sub)))} | ${f(mean(err('baseline', sub)))} |`;
});

const maeModel = mean(err('predicted'))!;
const maeBase = mean(err('baseline'))!;
const md = `# ETA evaluation (RQ2)

Generated by \`npm run eval:eta\` on ${new Date().toISOString().slice(0, 10)} · seed ${SEED} · ${SESSIONS} sessions per doctor (first session per doctor excluded as warm-up).

The simulator feeds synthetic arrivals, walk-ins and log-normal consultation durations through the **same** \`selectNext\`, \`predictOrder\`, \`estimateConsultDuration\` and \`computeEta\` functions the API uses. The prediction is taken at check-in; "actual" is check-in → called.

| Metric | Rolling-median ETA | Fixed 12-min baseline |
|---|---|---|
| Samples | ${rows.length} | ${rows.length} |
| Mean absolute error (min) | **${f(maeModel)}** | ${f(maeBase)} |
| Median absolute error (min) | ${f(median(err('predicted')))} | ${f(median(err('baseline')))} |
| 90th percentile error (min) | ${f(percentile(err('predicted'), 90))} | ${f(percentile(err('baseline'), 90))} |

Actual wait fell inside the displayed range (0.8×–1.25× estimate, ±1 min) for **${((inBand / rows.length) * 100).toFixed(1)}%** of patients.

## By doctor

| Doctor | True median consult (min) | Samples | ETA MAE (min) | Baseline MAE (min) |
|---|---|---|---|---|
${perDoctor.join('\n')}

## Reading the result

- The improvement is largest for doctors whose typical consultation differs from the 12-minute default (D02 faster, D03 slower), because the rolling median learns each doctor's pace while the baseline cannot.
- For a doctor whose real pace is close to the default (D01) the two methods are similar — the estimate is only as good as the queue is predictable.
- These are synthetic results. They show the algorithm behaves as designed; they are not a claim about any real clinic.
`;

const out = path.resolve(__dirname, '../../docs/results');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'eta-evaluation.md'), md);
fs.writeFileSync(path.join(out, 'eta-evaluation.json'), JSON.stringify({ seed: SEED, sessions: SESSIONS, maeModel, maeBase, samples: rows.length, rows }, null, 2));
console.log(md);
console.log(`Written to ${path.join(out, 'eta-evaluation.md')}`);
